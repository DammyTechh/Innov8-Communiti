/**
 * Refreshes the reference lists used by onboarding auto-verification:
 *   - world universities and their email domains (github.com/Hipo/university-domains-list)
 *   - disposable / throwaway email domains (github.com/disposable-email-domains/disposable-email-domains)
 *
 *   npx tsx scripts/update-verification-data.ts
 *
 * Both lists are written as packed strings (one entry per line) so TypeScript does not have to
 * infer a type for 10,000 array elements; they are parsed once, lazily, at runtime.
 */
import { writeFileSync } from 'node:fs';

const UNIS = 'https://raw.githubusercontent.com/Hipo/university-domains-list/master/world_universities_and_domains.json';
const DISPOSABLE = 'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';
const out = new URL('../src/modules/verification/data/', import.meta.url).pathname;

interface Uni {
  name: string;
  alpha_two_code: string;
  domains: string[];
}

const clean = (s: string) => s.replace(/[|\n\r`$\\]/g, ' ').replace(/\s+/g, ' ').trim();

const unis = (await (await fetch(UNIS)).json()) as Uni[];
const seen = new Set<string>();
const uniLines: string[] = [];
for (const u of unis) {
  const domains = [...new Set(u.domains.map((d) => d.trim().toLowerCase()).filter((d) => /^[a-z0-9.-]+\.[a-z]{2,}$/.test(d)))];
  const key = `${u.name}|${u.alpha_two_code}`;
  if (!domains.length || seen.has(key)) continue;
  seen.add(key);
  uniLines.push(`${clean(u.name)}|${u.alpha_two_code}|${domains.join(',')}`);
}
uniLines.sort();

const disposable = (await (await fetch(DISPOSABLE)).text())
  .split('\n')
  .map((l) => l.trim().toLowerCase())
  .filter((l) => l && !l.startsWith('#') && /^[a-z0-9.-]+$/.test(l))
  .sort();

const header = (source: string) => `// Generated by scripts/update-verification-data.ts from ${source}. Do not edit by hand.\n`;
writeFileSync(`${out}universities.ts`, `${header(UNIS)}// name|ISO country|domain[,domain]\nexport const UNIVERSITIES = \`${uniLines.join('\n')}\`;\n`);
writeFileSync(`${out}disposable-domains.ts`, `${header(DISPOSABLE)}export const DISPOSABLE_DOMAINS = \`${disposable.join('\n')}\`;\n`);
console.log(`universities: ${uniLines.length}, disposable domains: ${disposable.length}`);
